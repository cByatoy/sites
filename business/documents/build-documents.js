// Поля для заполнения пишутся в [квадратных скобках] и подсвечиваются жёлтым.

const fs = require('fs');
const path = require('path');
const {
  Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell,
  AlignmentType, WidthType, BorderStyle, PageBreak, Footer, PageNumber,
} = require('docx');

const OUT = path.join(__dirname, 'docx');
const FONT = 'Times New Roman';
const SIZE = 22; // 11 pt
const TABLE_W = 9638; // A4 с полями 2 см

// ---------- helpers ----------

function runs(text, opts = {}) {
  return text.split(/(\[[^\]]+\])/).filter(Boolean).map((part) =>
    new TextRun({
      text: part, font: FONT, size: opts.size || SIZE, bold: opts.bold, italics: opts.italics,
      highlight: part.startsWith('[') ? 'yellow' : undefined,
    }));
}

const p = (text, opts = {}) => new Paragraph({
  children: runs(text, opts),
  alignment: opts.align || AlignmentType.JUSTIFIED,
  spacing: { after: opts.after ?? 80, line: 264 },
  indent: opts.indent ? { firstLine: 0, left: opts.indent } : undefined,
  keepNext: opts.keepNext,
});

const title = (text) => p(text, { bold: true, size: 26, align: AlignmentType.CENTER, after: 60 });
const center = (text, opts = {}) => p(text, { align: AlignmentType.CENTER, ...opts });
const section = (text) => p(text, { bold: true, align: AlignmentType.CENTER, after: 100, keepNext: true });
const blank = () => p('', { after: 0 });
const pageBreak = () => new Paragraph({ children: [new PageBreak()] });

// Нумерованные пункты: clauses(3, ['текст', 'текст', ...]) → 3.1., 3.2., ...
// Строка, начинающаяся с '- ', становится подпунктом без номера.
function clauses(n, items) {
  let i = 0;
  return items.filter(Boolean).map((t) => {
    if (t.startsWith('- ')) return p('— ' + t.slice(2), { indent: 567 });
    i += 1;
    return p(`${n}.${i}. ${t}`);
  });
}

const border = { style: BorderStyle.SINGLE, size: 4, color: '000000' };
const borders = { top: border, bottom: border, left: border, right: border };
const noBorder = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
const noBorders = { top: noBorder, bottom: noBorder, left: noBorder, right: noBorder };

function table(widths, rows, { header = true, bordered = true } = {}) {
  return new Table({
    width: { size: TABLE_W, type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((cells, r) => new TableRow({
      children: cells.map((c, i) => new TableCell({
        width: { size: widths[i], type: WidthType.DXA },
        borders: bordered ? borders : noBorders,
        margins: { top: 60, bottom: 60, left: 100, right: 100 },
        children: (Array.isArray(c) ? c : [c]).map((line) =>
          p(line, { bold: header && r === 0, align: AlignmentType.LEFT, after: 20 })),
      })),
    })),
  });
}

function save(name, children) {
  const doc = new Document({
    styles: { default: { document: { run: { font: FONT, size: SIZE } } } },
    sections: [{
      properties: { page: { margin: { top: 1134, bottom: 1134, left: 1134, right: 1134 } } },
      footers: {
        default: new Footer({
          children: [new Paragraph({
            alignment: AlignmentType.RIGHT,
            children: [new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: 18 })],
          })],
        }),
      },
      children,
    }],
  });
  return Packer.toBuffer(doc).then((buf) => fs.writeFileSync(path.join(OUT, name), buf));
}

